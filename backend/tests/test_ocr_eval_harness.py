"""Fast pytest wrapper around the OCR evaluation harness (backend/eval/).

CI does NOT run the full eval sweep (3 configs x 5 fixtures x real PaddleOCR inference is slow -
see eval/run_ocr_eval.py and eval/ocr_eval_report.md for the full results). This test only
exercises the harness's pure-Python scoring functions (no model inference, deterministic,
instant) plus - gated behind RUN_REAL_OCR_TESTS=1 like the rest of the real-inference tests in
test_paddle_ocr.py - a single real fixture/config smoke run through the full harness pipeline.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(os.path.dirname(HERE), "eval"))

import pytest

from run_ocr_eval import cer, wer, _critical_field_hits, load_fixtures, SYNTH_DIR


def test_cer_identical_strings_is_zero():
    assert cer("45.25mm", "45.25mm") == 0.0


def test_cer_one_char_diff():
    assert cer("45.25mm", "45.26mm") == pytest.approx(1 / 7)


def test_wer_word_level():
    assert wer("DRAWING NO MB-100", "DRAWING NO MB-200") == pytest.approx(1 / 3)


def test_critical_field_hits_case_and_whitespace_insensitive():
    hits = _critical_field_hits("Drawing No:  mb-10045-rev-c  extra text", {"drawing_number": "MB-10045-REV-C"})
    assert hits == {"drawing_number": True}


def test_critical_field_miss_detected():
    hits = _critical_field_hits("totally unrelated text", {"drawing_number": "MB-10045-REV-C"})
    assert hits == {"drawing_number": False}


def test_fixtures_directory_has_ground_truth_for_every_data_file():
    fixtures = load_fixtures()
    assert len(fixtures) >= 5, "expected synthetic fixtures generated by generate_fixtures.py"
    for stem, path, gt in fixtures:
        assert os.path.exists(path)
        assert gt.get("full_text") or gt.get("pages"), f"{stem} ground truth missing full_text/pages"


def test_real_dir_is_empty_placeholder_not_mislabeled_synthetic():
    real_dir = os.path.join(os.path.dirname(SYNTH_DIR), "real")
    entries = [e for e in os.listdir(real_dir) if e != "README.md"]
    assert entries == [], "real/ must stay empty until genuine annotated drawings are added"


@pytest.mark.skipif(os.environ.get("RUN_REAL_OCR_TESTS") != "1",
                     reason="Set RUN_REAL_OCR_TESTS=1 to run one real fixture through PaddleOCR.")
def test_real_eval_harness_single_fixture_smoke():
    """One real (unmocked) PaddleOCR run through the actual eval harness code path, proving the
    harness is wired to genuine inference and not just to its own scoring helpers."""
    from app.services.paddle_ocr import run_page_ocr
    import cv2

    fixtures = load_fixtures()
    stem, path, gt = fixtures[0]
    image = cv2.imread(path)
    result = run_page_ocr(image, page_number=1)
    assert result.configured is True
    assert result.regions, "expected at least one recognized region on a real fixture"
