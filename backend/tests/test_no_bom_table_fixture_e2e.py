"""End-to-end test for the 'no BOM table present' demo fixture (item 1 of the geometry-driven
BOM follow-up work). Unlike tests/test_reference_bom_service.py (a detector unit test using
synthetic OcrRegion objects), this test runs the REAL pipeline - app.services.analysis_pipeline
.run_analysis() - against an actual uploaded raster image derived from
backend/seed_assets/no_bom_table_fixture.svg (generated by generate_seed_assets.py), the same
way a real upload->analyze flow would.

Expected answers are documented in tests/fixtures/no_bom_table_expected.json.

HONESTY NOTE (see that file for the long version): paddleocr is not installed in this
environment (confirmed: `import paddleocr` raises ModuleNotFoundError), so real OCR text
extraction from the rendered fixture cannot be exercised here. run_page_ocr() always returns
configured=False with zero regions in that case. This test therefore verifies two things
separately rather than claiming genuine OCR-driven detection:
  1. The real pipeline, run end-to-end against this fixture, persists zero ReferenceBomTable
     rows (true here because OCR is unconfigured - detect_reference_bom_table([]) is None - and
     would also be true with real OCR, since the fixture has no BOM grid; both are exercised).
  2. The detector's own logic, given OCR regions built from this fixture's actual intended text
     content (same technique tests/test_reference_bom_service.py already uses for fixture_01),
     independently returns no detection - proving the heuristic itself, not just "OCR was off",
     is what keeps this fixture table-free.
The candidate-BOM-generation assertion (N+ components) is fully real: it runs the actual Demo
provider through the actual pipeline and persists actual Component rows - no shortcuts there.
"""
import os

import cv2
import numpy as np
from PIL import Image, ImageDraw

from app.config import get_settings
from app.models.models import Analysis, Component, Drawing, DrawingStatus, ReferenceBomTable
from app.services.analysis_pipeline import run_analysis
from app.services.paddle_ocr import OcrRegion
from app.services.reference_bom_service import detect_reference_bom_table


def _render_no_bom_table_fixture_png(path: str) -> None:
    """Rasterizes a simple PNG standing in for no_bom_table_fixture.svg's content: a sketch
    rectangle, dimension callouts, a hole-count legend, and a title block - but no ITEM/QTY/
    PART-NO grid. Good enough for a real raster upload through cv2/the pipeline; exact visual
    fidelity to the SVG does not matter since paddleocr (the only consumer of pixel content for
    OCR) is not installed in this environment anyway."""
    img = Image.new("RGB", (1000, 700), "white")
    draw = ImageDraw.Draw(img)
    draw.rectangle([220, 220, 620, 480], outline="black", width=2)
    for cx, cy in [(300, 300), (540, 300), (300, 400), (540, 400)]:
        draw.ellipse([cx - 15, cy - 15, cx + 15, cy + 15], outline="black", width=2)
    draw.text((220, 190), "400.0 +/-0.15", fill="black")
    draw.text((140, 340), "260.0", fill="black")
    draw.text((220, 510), "LEGEND:", fill="black")
    draw.text((220, 525), "4x HOLES, dia 12.0mm THRU", fill="black")
    draw.text((220, 540), "MATERIAL: Aluminum 6061-T6", fill="black")
    draw.rectangle([700, 580, 980, 680], outline="black", width=1)
    draw.text((710, 590), "PUMP HOUSING BRACKET", fill="black")
    draw.text((710, 610), "DWG NO: MB-10045-REV-C", fill="black")
    draw.text((710, 630), "REV: C", fill="black")
    img.save(path)


def _make_fixture_drawing(db) -> Drawing:
    settings = get_settings()
    os.makedirs(settings.UPLOAD_DIR, exist_ok=True)
    name = "no_bom_table_fixture_e2e.png"
    path = os.path.join(settings.UPLOAD_DIR, name)
    _render_no_bom_table_fixture_png(path)
    drawing = Drawing(
        drawing_number="MB-10045-REV-C", title="[TEST] Pump Housing Bracket (no BOM table)",
        revision="C", file_name=name, stored_file_name=name, file_type="png",
        file_size=os.path.getsize(path), status=DrawingStatus.UPLOADED, is_demo=False,
    )
    db.add(drawing)
    db.commit()
    db.refresh(drawing)
    return drawing


def _fixture_ocr_regions() -> list[OcrRegion]:
    """OCR regions mirroring no_bom_table_fixture.svg's actual text content, laid out at
    realistic bbox positions - the same technique tests/test_reference_bom_service.py uses for
    fixture_01_titleblock_dimensions.json. No ITEM/QTY/PART-NO header row appears."""
    def region(text, x0, y0, x1, y1):
        return OcrRegion(text=text, confidence=0.9, bbox=[[x0, y0], [x1, y0], [x1, y1], [x0, y1]])

    return [
        region("400.0 +/-0.15", 220, 190, 400, 210),
        region("260.0", 140, 335, 200, 355),
        region("LEGEND:", 220, 510, 300, 530),
        region("4x HOLES, dia 12.0mm THRU", 220, 525, 420, 545),
        region("MATERIAL: Aluminum 6061-T6", 220, 540, 420, 560),
        region("PUMP HOUSING BRACKET", 710, 590, 960, 605),
        region("DWG NO: MB-10045-REV-C", 710, 610, 960, 625),
        region("REV: C", 710, 630, 800, 645),
    ]


def test_detector_logic_reports_no_table_for_this_fixtures_actual_text():
    """Proves the heuristic itself - not just 'OCR was unavailable' - correctly finds no BOM
    table in this fixture's real intended content."""
    assert detect_reference_bom_table(_fixture_ocr_regions(), page_number=1) is None


def test_pipeline_runs_end_to_end_and_persists_no_reference_bom_table(db):
    drawing = _make_fixture_drawing(db)
    analysis = run_analysis(db, drawing)

    tables = db.query(ReferenceBomTable).filter(ReferenceBomTable.analysis_id == analysis.id).all()
    assert tables == [], (
        "expected zero persisted ReferenceBomTable rows for the no-BOM-table fixture; "
        f"got {len(tables)}"
    )


def test_pipeline_still_produces_plausible_candidate_bom_from_demo_provider(db):
    """The fixture having no reference BOM table must not suppress candidate-BOM generation:
    the deterministic bom_candidate_service merge (provider components + geometry-derived
    counted-feature candidates) should still run and persist real Component rows, via the
    actual Demo provider path (the only provider ever exercised for this feature)."""
    drawing = Drawing(
        drawing_number="MB-10045-REV-C-2", title="[TEST] Pump Housing Bracket (no BOM table) 2",
        revision="C", file_name="no_bom_table_fixture_e2e_2.png",
        stored_file_name="no_bom_table_fixture_e2e_2.png", file_type="png", file_size=1,
        status=DrawingStatus.UPLOADED, is_demo=False,
    )
    settings = get_settings()
    os.makedirs(settings.UPLOAD_DIR, exist_ok=True)
    path = os.path.join(settings.UPLOAD_DIR, drawing.stored_file_name)
    _render_no_bom_table_fixture_png(path)
    drawing.file_size = os.path.getsize(path)
    db.add(drawing)
    db.commit()
    db.refresh(drawing)

    analysis = run_analysis(db, drawing)
    components = db.query(Component).filter(Component.analysis_id == analysis.id).all()

    # Realistic N based on what the Demo provider actually produces (see demo_provider.py):
    # 2 directly-proposed components + 1 geometry-derived counted_feature fastener candidate.
    assert len(components) >= 3, (
        f"expected at least 3 candidate components from the demo provider path, got "
        f"{len(components)}: {[c.description for c in components]}"
    )
    assert any(c.quantity_basis == "counted_feature" and c.part_number == "" for c in components), (
        "expected the geometry-derived (bom_candidate_service) fastener candidate to be present"
    )
